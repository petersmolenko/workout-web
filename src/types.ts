/**
 * Типы данных тренировок.
 *
 * Описывает структуру файлов:
 *  - db/workouts.json   — история тренировок (2021–2023) и будущие тренировки
 *  - db/exercises.json  — канонический справочник упражнений
 *
 * Ключевая идея модели: у каждого упражнения в тренировке два состояния —
 * «план» (что назначено) и «факт» (что реально сделано). Для исторических
 * тренировок 2021–2023 известен только план; факт заполняется в новых
 * тренировках после отчёта.
 */

/** Конечный набор групп мышц (совпадает с exercises.json → groups). */
export type MuscleGroup =
  | "Грудь"
  | "Спина"      // включает поясницу (подгруппа "поясница")
  | "Ноги"
  | "Плечи"      // включает трапецию (подгруппа "трапеция")
  | "Бицепс"
  | "Трицепс"
  | "Пресс"
  | "Кардио/ОФП";

/** Оборудование. */
export type Equipment =
  | "штанга"
  | "гантели"
  | "блок"      // кроссовер / блочные тяги
  | "тренажёр"  // рычажные, Смит, гравитрон и т.п.
  | "свой вес"
  | "блин"
  | "канат";

/** Запись справочника упражнений (exercises.json → exercises[]). */
export interface ExerciseDef {
  /** Стабильный идентификатор, напр. "leg_ext", "bench_bb". */
  id: string;
  /** Каноническое название, напр. "Разгибания ног сидя". */
  name: string;
  group: MuscleGroup;
  /** Уточнение внутри группы: "квадрицепс", "задняя дельта", "поясница"… */
  subgroup: string | null;
  equipment: Equipment;
  /** Сколько раз упоминалось в истории 2021–2023 (для сортировок). */
  mentions: number;
  /** Все исходные формулировки тренера, сведённые к этому упражнению. */
  aliases: string[];
}

/** Файл exercises.json целиком. */
export interface ExerciseDictionary {
  groups: MuscleGroup[];
  exercises: ExerciseDef[];
}

// ---------------------------------------------------------------------------
// Веса и подходы
// ---------------------------------------------------------------------------

/**
 * Единица измерения веса. ВАЖНО: единицы не взаимно конвертируемы,
 * сравнивать прогрессию можно только внутри одной единицы.
 */
export type WeightUnit =
  /** Общий вес снаряда, кг (штанга целиком, гантель, рукоять с блинами). */
  | "kg"
  /** Кг на КАЖДУЮ сторону грифа (тренер часто писал «по 10 кг на сторону»).
   *  Полный вес штанги ≈ value × 2 + гриф (обычно 20 кг). */
  | "kg_per_side"
  /** Плитки блочного тренажёра/кроссовера. Вес одной плитки зависит от
   *  тренажёра (~4,5–7 кг), поэтому хранится счётчик, а не кг. */
  | "plates"
  /** Блины, надетые на снаряд/тренажёр, счётчиком («6-8 блинов»). */
  | "discs"
  /** Без отягощения (отжимания, выпады без веса, планка без времени). */
  | "bodyweight"
  /** Длительность в секундах (планка, канат, лыжи). value = секунды. */
  | "seconds";

/** Вес в одном подходе. */
export interface Weight {
  /** Числовое значение (нижняя граница, если диапазон). null — если из
   *  текста не извлечь число (см. raw), напр. «пустой гриф», «средний вес». */
  value: number | null;
  /** Верхняя граница диапазона («3-4 плитки» → value 3, valueMax 4). */
  valueMax?: number;
  unit: WeightUnit;
  /** Исходный текст, если вес нечисловой или неоднозначный. */
  raw?: string;
}

/** Повторения в одном подходе. */
export interface Reps {
  /** Нижняя граница. null — если повторения не заданы числом («в отказ»). */
  min: number | null;
  /** Верхняя граница диапазона («8-12» → min 8, max 12). Если не диапазон,
   *  max === min. */
  max: number | null;
}

/** Один подход (плановый или фактический). */
export interface WorkoutSet {
  weight: Weight | null;
  reps: Reps | null;
  /** Подход выполняется до отказа («в отказ», «×макс», «по максимуму»). */
  toFailure?: boolean;
  /** Разминочный подход. */
  warmup?: boolean;
  /** Свободный комментарий к подходу («умеренный отказ», «с паузой 1 с»). */
  comment?: string;
}

// ---------------------------------------------------------------------------
// План и факт упражнения
// ---------------------------------------------------------------------------

/** Плановая часть упражнения — что назначено. */
export interface ExercisePlan {
  /**
   * Исходная строка плана ЦЕЛИКОМ (схема + веса + примечания).
   * Никогда не теряется — это источник истины при спорном парсинге.
   * Пример: "3×15 | 3-4 / 4 / 5 плиток, 3-й подход в отказ".
   */
  raw: string;
  /**
   * true — sets[] полностью восстановлены из raw;
   * false — разобрать автоматически не удалось, ориентироваться на raw
   *         (sets может быть пустым или частичным).
   */
  parsed: boolean;
  /** Количество подходов (null, если не определено). */
  setsCount: number | null;
  /** Подходы по порядку. Длина === setsCount при parsed === true. */
  sets: WorkoutSet[];
}

/**
 * Фактическая часть — что реально сделано. Заполняется из отчёта после
 * тренировки. У исторических тренировок (source === "trainer_history")
 * всегда null: факт неизвестен.
 */
export interface ExerciseFact {
  /** Выполненные подходы (вес/повторения — реальные). */
  sets: WorkoutSet[];
  /** Комментарий по упражнению («последний подход тяжело», «болело плечо»). */
  comment?: string;
  /** Упражнение пропущено целиком. */
  skipped?: boolean;
}

/** Упражнение внутри тренировки. */
export interface WorkoutExercise {
  /** Сквозной номер в тренировке (как в плане тренера), с 1. */
  order: number;
  /**
   * Ссылка на справочник (ExerciseDef.id). null — если формулировку
   * не удалось привязать к канону (см. rawName).
   */
  exerciseId: string | null;
  /** Каноническое название (денормализовано для удобства чтения). */
  exerciseName: string | null;
  /** Исходная формулировка из плана тренера. */
  rawName: string;
  /** Примечание к упражнению («средняя постановка ног», «пояс обязательно»). */
  note: string | null;
  plan: ExercisePlan;
  fact: ExerciseFact | null;
}

// ---------------------------------------------------------------------------
// Блоки и тренировка
// ---------------------------------------------------------------------------

/**
 * Блок — единица выполнения. "single" — одно упражнение; "superset"/"triset" —
 * 2–3 упражнения, выполняемые подряд без отдыха (отдых после круга).
 */
export interface WorkoutBlock {
  type: "single" | "superset" | "triset";
  /** Пояснение к блоку из плана («подряд, без отдыха», «пауза 15-20 с»). */
  label?: string;
  exercises: WorkoutExercise[];
}

/** Статус тренировки. */
export type WorkoutStatus =
  /** Назначена, ещё не выполнена (новые тренировки). */
  | "planned"
  /** Выполнена. Для истории 2021–2023 ставится условно: тренировки
   *  считаются выполненными, но фактические результаты неизвестны. */
  | "completed"
  | "skipped";

/** Происхождение тренировки. */
export type WorkoutSource =
  /** Восстановлена из переписки с тренером (2021–2023). */
  | "trainer_history"
  /** Сгенерирована (Claude API). */
  | "generated"
  /** Создана вручную. */
  | "manual";

export interface Workout {
  /** Уникальный id, напр. "w-2021-04-20". При двух тренировках в один день —
   *  суффикс: "w-2021-04-20-2". */
  id: string;
  /** Дата в ISO-формате YYYY-MM-DD. Для истории — дата ПУБЛИКАЦИИ плана
   *  тренером (сама тренировка обычно была на следующий день). */
  date: string;
  /** Заголовок как в плане: "Ноги, плечи (суперсеты)". */
  title: string;
  /** Нормализованные группы мышц, извлечённые из заголовка. */
  muscleGroups: MuscleGroup[];
  status: WorkoutStatus;
  source: WorkoutSource;
  blocks: WorkoutBlock[];
  /** Кардио-задание («Велосипед 30 мин, пульс 130») или null. */
  cardio: string | null;
  /** Заметки тренера/свои: диета, спортпит, указания. */
  notes: string | null;
  /** Общий фидбек по тренировке (заполняется после выполнения). */
  feedback: string | null;
}

/** Файл workouts.json целиком. */
export interface WorkoutsFile {
  /** Версия схемы данных. Увеличивается при несовместимых изменениях. */
  version: number;
  /** Когда сгенерирован файл (ISO datetime). */
  generatedAt: string;
  /** Источники, из которых собраны данные. */
  sources: string[];
  /** Тренировки, отсортированы по дате по возрастанию. */
  workouts: Workout[];
}
